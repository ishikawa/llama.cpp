#!/usr/bin/env python3
"""Generate and exhaustively check the compact IQ2_S Metal lookup table."""
import argparse
from pathlib import Path
import re

BEGIN = '// BEGIN GENERATED IQ2S COMPACT GRID'
END = '// END GENERATED IQ2S COMPACT GRID'


def spread4(code):
    value = code & 255
    value = (value | (value << 12)) & 0x000f000f
    value = (value | (value << 6)) & 0x03030303
    return 0x08080808 + 17*value + ((value >> 1) & 0x01010101)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check the generated source without changing it')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    source = (root.parent / 'ggml-common.h').read_text()
    body = source.split('GGML_TABLE_BEGIN(uint64_t, iq2s_grid, 1024)', 1)[1].split('GGML_TABLE_END()', 1)[0]
    entries = [int(value, 16) for value in re.findall(r'0x([0-9a-fA-F]+)', body)]
    original = b''.join(value.to_bytes(8, 'little') for value in entries)
    if len(entries) != 1024 or set(original) != {8, 25, 43}:
        raise ValueError(f'expected 1024 entries containing only 8, 25, 43; got {len(entries)}, {set(original)}')
    codes = {8: 0, 25: 1, 43: 2}
    compact = [sum(codes[value] << (2*j) for j, value in enumerate(original[i:i+8])) for i in range(0, len(original), 8)]
    decoded = bytes(8 + 17*((value >> (2*j)) & 3) + (((value >> (2*j)) & 3) >> 1) for value in compact for j in range(8))
    spread = b''.join(spread4(value).to_bytes(4, 'little') + spread4(value >> 8).to_bytes(4, 'little') for value in compact)
    if decoded != original or spread != original:
        raise ValueError('compact table decoding differs from iq2s_grid')
    # Check the packed arithmetic for all possible four-element combinations.
    for packed in range(256):
        expected = bytes(8 + 17*((packed >> (2*j)) & 3) + (((packed >> (2*j)) & 3) >> 1) for j in range(4))
        if spread4(packed).to_bytes(4, 'little') != expected:
            raise ValueError('four-code expansion failed')
    rows = [', '.join(f'0x{value:04x}' for value in compact[i:i+16]) for i in range(0, len(compact), 16)]
    generated = BEGIN + '\n// Generated by ggml/src/ggml-metal/generate_iq2s_grid.py.\nconstant ushort iq2s_grid_compact[1024] = {\n'
    generated += ''.join(f'    {row},\n' for row in rows) + '};\n' + END
    target = root / 'kernels/mul_mv.metal'
    text = target.read_text()
    if BEGIN not in text or END not in text:
        if args.check:
            raise ValueError('generated table is missing')
        text = text.replace('#include "dequantize.h"', '#include "dequantize.h"\n\n' + BEGIN + '\n' + END, 1)
    start = text.index(BEGIN)
    end = text.index(END, start) + len(END)
    updated = text[:start] + generated + text[end:]
    if args.check:
        if updated != text:
            raise ValueError('generated table is stale; run this script without --check')
    else:
        target.write_text(updated)
    print('IQ2_S compact grid: all 8192 bytes reproduced; packed expansion checked for all 256 inputs')


if __name__ == '__main__':
    main()
